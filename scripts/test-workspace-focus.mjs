import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {searchWorkspaceSites,footprintAssets} from '../lib/workspace-focus.ts';
import {buildSiteGraph,buildFootprintGraph} from '../lib/knowledge-graph.ts';
const boot=JSON.parse(await fs.readFile('work/pages-public/snapshot/bootstrap.json','utf8'));
const detail=JSON.parse(await fs.readFile('work/pages-public/snapshot/sites/G-6.json','utf8'));
assert.deepEqual(searchWorkspaceSites(boot.sites,'豫园').map(s=>s.id),['G-6']);
assert.equal(searchWorkspaceSites(boot.sites,'安仁街218号')[0].id,'G-6');
assert.equal(searchWorkspaceSites(boot.sites,'豫园 黄浦')[0].id,'G-6');
assert.equal(searchWorkspaceSites(boot.sites,'豫园','徐汇').length,0);
assert.equal(searchWorkspaceSites(boot.sites,'missing-place-98765').length,0);
assert.ok(searchWorkspaceSites(boot.sites,'黄浦').length>50);
assert.ok(searchWorkspaceSites(boot.sites,'g-6').some(s=>s.id==='G-6'));
assert.equal(searchWorkspaceSites(boot.sites,'').length,767);
assert.deepEqual(footprintAssets([{id:'a',building_id:123},{id:'b',building_id:'123'},{id:'c',building_id:null}], '123').map(s=>s.id),['a','b']);
assert.equal(footprintAssets([{id:'a',building_id:null}], 'null').length,0);
const g=buildSiteGraph(detail),building=g.nodes.find(n=>n.kind==='building'),spatial=g.edges.find(e=>e.kind==='spatial');
assert.equal(building.buildingId,String(detail.spatial.building_id));assert.equal(building.siteId,'G-6');assert.equal(spatial.siteId,'G-6');assert.match(spatial.label,/面内/);
const candidate=buildSiteGraph({...detail,spatial:{...detail.spatial,status:'candidate'}});assert.match(candidate.edges.find(e=>e.kind==='spatial').label,/待核查/);
for(const height of [null,undefined,NaN,Infinity])assert.equal(buildFootprintGraph({building_id:'123',height}).nodes.length,2);
const unlinked=buildFootprintGraph({building_id:'123',height:12});assert.equal(unlinked.nodes.length,3);assert.equal(unlinked.nodes.filter(n=>n.kind==='site'||n.kind==='indicator').length,0);assert.ok(unlinked.nodes.every(n=>!n.siteId));assert.equal(unlinked.nodes.find(n=>n.kind==='source').label,'上海建筑.zip');
console.log('PASS: local place search; multiple footprint associations; real spatial provenance; no fabricated heritage data for unlinked buildings.');
